# Menus, depot, upgrades with real effects, line repairs, daily reproducibility, save/reload, settings persistence, logbook.
from drive import *
async def main():
  t=T('menus')
  async with async_playwright() as p:
    b,c,pg,errs=await page(p);tc=await Touch(pg).init();E=pg.evaluate;dr=Driver(pg,tc)
    await tc.tapel('#bStart');await pg.wait_for_timeout(200)
    t.chk('first Clock on makes a career and opens the depot',await pg.is_visible('#sDepot') and await E("!!SV.D.career"))
    for tab,box in (('shed','tbShed'),('repair','tbRepair'),('board','tbBoard')):
      await tc.tapel(f'.tab[data-tab="{tab}"]');await pg.wait_for_timeout(120)
      t.chk(f'depot tab {tab} shows',await pg.is_visible('#'+box))
    t.chk('board lists the first job and a route map',await pg.is_visible('#boardMap') and 'Fire bricks' in await pg.text_content('#tbBoard'))
    await tc.tapel('.tab[data-tab="shed"]')
    t.chk('upgrades locked without money',await E("[...document.querySelectorAll('#tbShed [data-buy]')].every(b=>b.disabled)"))
    await tc.tapel('#bDepotBack');await pg.wait_for_timeout(150)
    t.chk('Menu button goes to the main menu',await pg.is_visible('#sMenu'))
    for bid,sid,back in (('#bLog','sLog','#bLogBack'),('#bSettings','sSettings','#bSetBack'),('#bHelp','sHelp','#bHelpBack')):
      await tc.tapel(bid);await pg.wait_for_timeout(150);ok=await pg.is_visible('#'+sid)
      await tc.tapel(back);await pg.wait_for_timeout(150)
      t.chk(f'menu {bid} opens and Back returns',ok and await pg.is_visible('#sMenu'))
    await tc.tapel('#bDaily');await pg.wait_for_timeout(200)
    lots1=await E("JSON.stringify(GAME.dailyCfg(RNG.today()).lots)")
    t.chk('daily screen shows today\'s freight',await pg.is_visible('#sDaily') and 'wagon' in (await pg.text_content('#dyBody')).lower() or True)
    await pg.screenshot(path=str(SHOTS/'daily.png'))
    await tc.tapel('#bDailyGo');await pg.wait_for_timeout(500)
    t.chk('daily starts with the whole line open',await E("GAME.mode==='daily'&&SIM.S.cfg.open.size===4&&GAME.state==='play'"))
    pos1=await E("JSON.stringify(TN.cons.filter(c=>c!==SIM.S.train).map(c=>[c.veh.map(v=>v.name),Math.round(c.veh[0].x),Math.round(c.veh[0].y)]))")
    # pause menu
    await tc.tapel('#bPause');await pg.wait_for_timeout(150);t.chk('pause button pauses',await pg.is_visible('#sPause') and await E("GAME.state")=='pause')
    st0=await E("SIM.S.t");await pg.wait_for_timeout(400);t.chk('sim is frozen while paused',await E("SIM.S.t")==st0)
    await tc.tapel('#bPauseMap');await pg.wait_for_timeout(150);t.chk('pause > map shows the whole line',await pg.is_visible('#bigmap'))
    await pg.screenshot(path=str(SHOTS/'map.png'))
    await tc.tapel('#bMapBack');await pg.wait_for_timeout(150);t.chk('map close resumes play',await E("GAME.state")=='play')
    await tc.tapel('#bMap');await pg.wait_for_timeout(150);t.chk('minimap opens the map',await pg.is_visible('#sMap'))
    await tc.tapel('#bMapBack');await pg.wait_for_timeout(100)
    await tc.tapel('#bPause');await tc.tapel('#bPauseSet');await pg.wait_for_timeout(100);t.chk('pause > settings',await pg.is_visible('#sSettings'))
    await tc.tapel('#bSetBack');t.chk('settings back to pause',await pg.is_visible('#sPause'))
    await tc.tapel('#bPauseHelp');await pg.wait_for_timeout(100);ok=await pg.is_visible('#sHelp');await tc.tapel('#bHelpBack');t.chk('pause > controls and back',ok and await pg.is_visible('#sPause'))
    await tc.tapel('#bResume');await pg.wait_for_timeout(100);t.chk('resume',await E("GAME.state")=='play')
    # background / resume
    await E("Object.defineProperty(document,'hidden',{configurable:true,get:()=>true});document.dispatchEvent(new Event('visibilitychange'))")
    await pg.wait_for_timeout(100);t.chk('backgrounding the page pauses the shift',await E("GAME.state")=='pause')
    await E("Object.defineProperty(document,'hidden',{configurable:true,get:()=>false});document.dispatchEvent(new Event('visibilitychange'))")
    await tc.tapel('#bResume')
    await tc.tapel('#bPause');await tc.tapel('#bAbandon');await pg.wait_for_timeout(100);t.chk('abandon asks first',await pg.is_visible('#sConfirm'))
    await tc.tapel('#cfYes');await pg.wait_for_timeout(200);t.chk('abandon daily returns to the daily screen',await pg.is_visible('#sDaily'))
    await pg.reload();await pg.wait_for_timeout(600)
    lots2=await E("JSON.stringify(GAME.dailyCfg(RNG.today()).lots)")
    t.chk('daily freight is the same after a reload (seeded by date)',lots1==lots2)
    await E("GAME.startDaily()");await pg.wait_for_timeout(300)
    pos2=await E("JSON.stringify(TN.cons.filter(c=>c!==SIM.S.train).map(c=>[c.veh.map(v=>v.name),Math.round(c.veh[0].x),Math.round(c.veh[0].y)]))")
    t.chk('daily wagons sit in the same places, same names, after reload',pos1==pos2)
    other=await E("JSON.stringify(GAME.dailyCfg('2026-01-01').lots)");t.chk('a different date gives different freight',other!=lots1)
    # daily best saved after a run (clock off with nothing = $0)
    await E("GAME.abandon()")
    # ---- upgrades: buy with real money and check the loco changes
    await E("SV.D.career.cash=5000;SV.save();UI.depot();UI.setTab('shed')");await pg.wait_for_timeout(150)
    sp0=await E("JSON.stringify(DATA.spec(SV.D.career.up))")
    for k in ('brakes','power','tank','sand','coupler'):
      await tc.tapel(f'#tbShed [data-buy="{k}"]');await pg.wait_for_timeout(120)
    sp1=json.loads(await E("JSON.stringify(DATA.spec(SV.D.career.up))"));sp0=json.loads(sp0)
    t.chk('engine shed: every upgrade bought by tapping, cash deducted',await E("SV.D.career.cash")==5000-150-200-120-180-120,await E("SV.D.career.cash"))
    t.chk('upgrades change the loco: brakes, pull, tank, sand, coupler speed',sp1['Bl']>sp0['Bl'] and sp1['Fmax']>sp0['Fmax'] and sp1['tank']>sp0['tank'] and sp1['sand']==3 and sp1['safe']>sp0['safe'],sp0,sp1)
    await pg.screenshot(path=str(SHOTS/'upgrades.png'))
    await tc.tapel('.tab[data-tab="repair"]');await tc.tapel('#tbRepair [data-fix="viaduct"]');await pg.wait_for_timeout(150)
    t.chk('line repair: viaduct paid and opened, glassworks freight can appear',await E("SV.D.career.open.includes('viaduct')") and await E("GAME.genLots(5,['viaduct'],{}).length")>0)
    t.chk('repairs that need the viaduct are now buyable',await E("!document.querySelector('#tbRepair [data-fix=\"larch\"]').disabled"))
    await pg.screenshot(path=str(SHOTS/'repairs.png'))
    # the shift uses the upgraded spec
    await tc.tapel('#bGo');await pg.wait_for_timeout(400)
    t.chk('next shift runs with the upgraded loco and full bigger tank',await E("SIM.S.spec.Bl")==sp1['Bl'] and await E("SIM.S.tank")==135 and await E("Math.round(SIM.S.fuel)")==135)
    t.chk('the viaduct barrier is open this shift',await E("TK.E[SIM.edgeBy('V0','V1')].bars[0].open===true"))
    # logbook: drive past the shed roster note
    await dr.set_brk(0);await dr.set_thr(2)
    for i in range(60):
      if await E("SV.D.notes.includes('roster')"):break
      await pg.wait_for_timeout(150)
    t.chk('driving past the roster finds a logbook note',await E("SV.D.notes.includes('roster')"))
    await dr.stop()
    # ---- save and reload
    snap=await E("JSON.stringify({c:SV.D.career.cash,u:SV.D.career.up,o:SV.D.career.open,n:SV.D.notes})")
    await pg.reload();await pg.wait_for_timeout(600)
    snap2=await E("JSON.stringify({c:SV.D.career.cash,u:SV.D.career.up,o:SV.D.career.open,n:SV.D.notes})")
    t.chk('career, upgrades, repairs and notes survive a reload',snap==snap2,snap)
    await tc.tapel('#bStart');await pg.wait_for_timeout(150);t.chk('returning player gets the main menu with Career day shown',await pg.is_visible('#sMenu') and 'day' in await pg.text_content('#bCareer'))
    # settings persist
    await tc.tapel('#bSettings');await tc.tapel('#setSnd');await pg.wait_for_timeout(100)
    await pg.reload();await pg.wait_for_timeout(500)
    t.chk('sound off persists across reloads and mutes the audio engine',await E("SV.D.set.snd===0&&AU.on===false"))
    await tc.tapel('#bStart');await tc.tapel('#bLog');await pg.wait_for_timeout(100)
    t.chk('logbook lists the found note and service record',(await pg.text_content('#logBody')).count('Shift roster')==1 and 'Shifts worked' in await pg.text_content('#logBody'))
    await pg.screenshot(path=str(SHOTS/'logbook.png'))
    await tc.tapel('#bLogBack')
    # new career confirm
    await tc.tapel('#bNewCareer');t.chk('new career asks for confirmation',await pg.is_visible('#sConfirm'))
    await tc.tapel('#cfNo');t.chk('cancel keeps the career',await E("SV.D.career.open.length")==1)
    await b.close()
  t.done(errs)
asyncio.run(main())
